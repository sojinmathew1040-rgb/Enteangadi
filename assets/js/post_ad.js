async function detectPostLocation(ev) {
    const b = ev.currentTarget;
    const originalHTML = b.innerHTML;
    b.disabled = true;
    b.innerHTML = '<i class="fa fa-spinner fa-spin"></i>';

    try {
        const coords = await EnteangadiLocation.getCurrentCoordinates();
        const lat = coords.lat;
        const lng = coords.lng;
        const latInput = document.getElementById('latitude');
        const lngInput = document.getElementById('longitude');
        const locInput = document.getElementById('location_name');

        if (latInput) latInput.value = lat;
        if (lngInput) lngInput.value = lng;

        try {
            const r = await fetch(`https://nominatim.openstreetmap.org/reverse?format=json&lat=${lat}&lon=${lng}&zoom=10`);
            const d = await r.json();
            if (locInput) locInput.value = d.address.city || d.address.town || 'Current Location';
        } catch (e) {
            if (locInput) locInput.value = 'Current Location';
        }
    } catch (err) {
        console.error('Error fetching location:', err);
    } finally {
        b.disabled = false;
        b.innerHTML = originalHTML;
    }
}

// Dynamic loading of TensorFlow.js and NSFWJS for 18+ content filtering
let nsfwModel = null;
let modelLoadingPromise = null;

async function loadNSFWModel() {
    if (nsfwModel) return nsfwModel;
    if (modelLoadingPromise) return modelLoadingPromise;

    modelLoadingPromise = (async () => {
        try {
            if (typeof tf === 'undefined') {
                await loadScript('https://cdn.jsdelivr.net/npm/@tensorflow/tfjs@2.8.5/dist/tf.min.js');
            }
            if (typeof nsfwjs === 'undefined') {
                await loadScript('https://cdn.jsdelivr.net/npm/nsfwjs@2.4.2/dist/nsfwjs.min.js');
            }
            
            // Resolve absolute base path for local model hosting
            const baseUrl = (window.EnteangadiConfig && typeof window.EnteangadiConfig.baseUrl !== 'undefined') ? window.EnteangadiConfig.baseUrl : '..';
            const modelUrl = baseUrl + '/assets/models/nsfw/';
            
            // Load from locally hosted model files to prevent remote dependency down-times
            nsfwModel = await nsfwjs.load(modelUrl);
            return nsfwModel;
        } catch (e) {
            console.error("Failed to load NSFW detection model:", e);
            return null;
        }
    })();

    return modelLoadingPromise;
}

function loadScript(src) {
    return new Promise((resolve, reject) => {
        const script = document.createElement('script');
        script.src = src;
        script.onload = resolve;
        script.onerror = reject;
        document.head.appendChild(script);
    });
}

function checkImageNSFWWithModel(model, file) {
    return new Promise((resolve) => {
        const img = new Image();
        const dataURL = file.dataURL || (window.EnteangadiImageCache && window.EnteangadiImageCache[file.name]);
        const isDataURL = !!dataURL;
        img.src = dataURL || URL.createObjectURL(file);
        img.onload = async () => {
            try {
                const predictions = await model.classify(img);
                if (!isDataURL) {
                    URL.revokeObjectURL(img.src);
                }

                let nsfwScore = 0;
                for (const p of predictions) {
                    if (p.className === 'Porn' || p.className === 'Sexy' || p.className === 'Hentai') {
                        nsfwScore += p.probability;
                    }
                }
                // Flag as NSFW if the combined probability is 60% or higher
                resolve(nsfwScore >= 0.60);
            } catch (err) {
                console.error("Image classification error:", err);
                resolve(false);
            }
        };
        img.onerror = () => {
            if (!isDataURL) {
                try { URL.revokeObjectURL(img.src); } catch(e) {}
            }
            resolve(false);
        };
    });
}


let postPhotoItems = [];
let postDragSrcIndex = null;

function readFileAsDataURL(file) {
    return new Promise((resolve) => {
        const cached = file.dataURL || (window.EnteangadiImageCache && window.EnteangadiImageCache[file.name]);
        if (cached) {
            resolve(cached);
            return;
        }
        const reader = new FileReader();
        reader.onload = (e) => resolve(e.target.result);
        reader.onerror = () => resolve('');
        reader.readAsDataURL(file);
    });
}

function syncPostFilesInput() {
    const imagesInput = document.getElementById('images');
    const coverIdxInput = document.getElementById('cover_index');
    if (!imagesInput) return;

    if (postPhotoItems.length > 0 && !postPhotoItems.some(item => item.isCover)) {
        postPhotoItems[0].isCover = true;
    }

    const dt = new DataTransfer();
    let coverIndex = 0;
    postPhotoItems.forEach((item, idx) => {
        if (item.file) dt.items.add(item.file);
        if (item.isCover) coverIndex = idx;
    });
    imagesInput.files = dt.files;
    if (coverIdxInput) coverIdxInput.value = coverIndex;
}

function setPostPhotoCover(index) {
    if (index < 0 || index >= postPhotoItems.length) return;
    postPhotoItems.forEach((item, idx) => {
        item.isCover = (idx === index);
    });
    renderPostPhotoPreviews();
    if (typeof showToast === 'function') {
        showToast('Cover image updated.');
    }
}

function movePostPhoto(fromIndex, toIndex) {
    if (
        fromIndex === toIndex ||
        fromIndex < 0 ||
        toIndex < 0 ||
        fromIndex >= postPhotoItems.length ||
        toIndex >= postPhotoItems.length
    ) {
        return;
    }
    const [moved] = postPhotoItems.splice(fromIndex, 1);
    postPhotoItems.splice(toIndex, 0, moved);
    renderPostPhotoPreviews();
}

async function deletePostPhoto(index) {
    if (index < 0 || index >= postPhotoItems.length) return;
    const item = postPhotoItems[index];
    const confirmed = window.confirmPhotoDelete
        ? await window.confirmPhotoDelete({
            title: 'Delete Photo?',
            message: 'Are you sure you want to delete this photo?',
            imgSrc: item.src,
            yesText: 'Yes',
            noText: 'No'
        })
        : confirm('Are you sure you want to delete this photo?');

    if (!confirmed) return;

    const wasCover = item.isCover;
    postPhotoItems.splice(index, 1);
    if (wasCover && postPhotoItems.length > 0) {
        postPhotoItems[0].isCover = true;
    }
    renderPostPhotoPreviews();
    if (typeof showToast === 'function') {
        showToast('Photo deleted.');
    }
}

function renderPostPhotoPreviews() {
    const c = document.getElementById('image_preview_container');
    if (!c) return;

    syncPostFilesInput();
    c.innerHTML = '';

    postPhotoItems.forEach((item, idx) => {
        const card = document.createElement('div');
        card.className = 'preview-item' + (item.isCover ? ' is-cover' : '');
        card.draggable = true;
        card.dataset.index = idx;

        const badgeHtml = item.isCover
            ? `<span class="photo-badge cover-badge-pill"><i class="fa fa-star"></i> COVER</span>`
            : `<span class="photo-badge order-badge-pill">#${idx + 1}</span>`;

        card.innerHTML = `
            <div class="photo-thumb-area" title="Click to set as Cover Image">
                <img src="${item.src}" alt="Product Photo ${idx + 1}">
                ${badgeHtml}
                <button type="button" class="photo-delete-btn" title="Delete Photo">
                    <i class="fa fa-trash-alt"></i>
                </button>
            </div>
            <div class="photo-controls-bar">
                <button type="button" class="photo-ctrl-btn move-left" ${idx === 0 ? 'disabled' : ''} title="Move Left">
                    <i class="fa fa-chevron-left"></i>
                </button>
                <button type="button" class="photo-cover-select-btn ${item.isCover ? 'active' : ''}" title="Set as Cover Image">
                    ${item.isCover ? '<i class="fa fa-check-circle"></i> Cover' : 'Set Cover'}
                </button>
                <button type="button" class="photo-ctrl-btn move-right" ${idx === postPhotoItems.length - 1 ? 'disabled' : ''} title="Move Right">
                    <i class="fa fa-chevron-right"></i>
                </button>
            </div>
        `;

        const thumbArea = card.querySelector('.photo-thumb-area');
        const deleteBtn = card.querySelector('.photo-delete-btn');
        const moveLeftBtn = card.querySelector('.move-left');
        const moveRightBtn = card.querySelector('.move-right');
        const coverBtn = card.querySelector('.photo-cover-select-btn');

        if (thumbArea) {
            thumbArea.addEventListener('click', (e) => {
                if (e.target.closest('.photo-delete-btn')) return;
                setPostPhotoCover(idx);
            });
        }
        if (deleteBtn) {
            deleteBtn.addEventListener('click', (e) => {
                e.stopPropagation();
                deletePostPhoto(idx);
            });
        }
        if (moveLeftBtn) {
            moveLeftBtn.addEventListener('click', (e) => {
                e.stopPropagation();
                movePostPhoto(idx, idx - 1);
            });
        }
        if (moveRightBtn) {
            moveRightBtn.addEventListener('click', (e) => {
                e.stopPropagation();
                movePostPhoto(idx, idx + 1);
            });
        }
        if (coverBtn) {
            coverBtn.addEventListener('click', (e) => {
                e.stopPropagation();
                setPostPhotoCover(idx);
            });
        }

        // HTML5 Drag and Drop Reordering
        card.addEventListener('dragstart', (e) => {
            postDragSrcIndex = idx;
            card.classList.add('is-dragging');
            if (e.dataTransfer) {
                e.dataTransfer.effectAllowed = 'move';
                e.dataTransfer.setData('text/plain', String(idx));
            }
        });
        card.addEventListener('dragover', (e) => {
            e.preventDefault();
            if (e.dataTransfer) e.dataTransfer.dropEffect = 'move';
            if (postDragSrcIndex !== null && postDragSrcIndex !== idx) {
                card.classList.add('drag-over');
            }
        });
        card.addEventListener('dragleave', () => {
            card.classList.remove('drag-over');
        });
        card.addEventListener('drop', (e) => {
            e.preventDefault();
            card.classList.remove('drag-over');
            const fromIdx = postDragSrcIndex !== null ? postDragSrcIndex : parseInt(e.dataTransfer?.getData('text/plain') || '-1', 10);
            postDragSrcIndex = null;
            if (!isNaN(fromIdx) && fromIdx >= 0 && fromIdx !== idx) {
                movePostPhoto(fromIdx, idx);
            }
        });
        card.addEventListener('dragend', () => {
            postDragSrcIndex = null;
            document.querySelectorAll('#image_preview_container .preview-item').forEach(el => {
                el.classList.remove('is-dragging', 'drag-over');
            });
        });

        c.appendChild(card);
    });
}

async function previewImages() {
    const c = document.getElementById('image_preview_container');
    const imagesInput = document.getElementById('images');
    if (!c || !imagesInput) return;

    const files = Array.from(imagesInput.files || []);
    if (files.length === 0) {
        syncPostFilesInput();
        return;
    }

    // Show beautiful premium scanner overlay
    const loader = document.getElementById('loadingOverlay');
    const loaderTitle = document.getElementById('loaderTitle') || loader?.querySelector('h3');
    const loaderDesc = document.getElementById('loaderDesc') || loader?.querySelector('p');

    if (loader) {
        if (loaderTitle) loaderTitle.innerText = "Safety Scanning";
        if (loaderDesc) loaderDesc.innerText = "Scanning selected images for community guidelines safety...";
        loader.style.display = 'flex';
    }

    let model = null;
    try {
        model = await loadNSFWModel();
    } catch (e) {
        console.error("Failed to fetch model:", e);
    }

    for (let i = 0; i < files.length; i++) {
        const file = files[i];

        // Exclude video files on client-side
        if (file.type.startsWith('video/')) {
            alert(`Videos are not allowed: ${file.name}`);
            continue;
        }

        let isNSFW = false;
        if (model && file.type.startsWith('image/')) {
            try {
                isNSFW = await checkImageNSFWWithModel(model, file);
            } catch (err) {
                console.error("Error analyzing safety of:", file.name, err);
            }
        }

        if (isNSFW) {
            alert(`Inappropriate Content Blocked: Image "${file.name}" contains content violating our 18+ policy and has been removed from selection.`);
            continue;
        }

        const dataURL = await readFileAsDataURL(file);
        postPhotoItems.push({
            id: 'post_' + Date.now() + '_' + Math.random().toString(36).slice(2, 7),
            file: file,
            src: dataURL,
            isCover: postPhotoItems.length === 0
        });
    }

    // Hide scanning overlay
    if (loader) {
        loader.style.display = 'none';
        if (loaderTitle) loaderTitle.innerText = "Publishing Ad";
        if (loaderDesc) loaderDesc.innerText = "Please wait while we set everything up...";
    }

    renderPostPhotoPreviews();
}

