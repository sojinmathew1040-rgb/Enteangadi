function autoSuggestTitle() {
    const titleEl = document.getElementById('title');
    if (!titleEl) return;
    const brand = document.getElementById('brand_select')?.value || '';
    const model = document.getElementById('model_select')?.value || '';
    const variant = document.getElementById('variant_select')?.value || '';

    const parts = [brand, model, variant].filter(p => p.trim().length > 0);
    if (parts.length > 0) {
        const suggested = parts.join(' ');
        if (!titleEl.value.trim() || titleEl.dataset.autoGenerated === 'true') {
            titleEl.value = suggested;
            titleEl.dataset.autoGenerated = 'true';
        }
    }
}

